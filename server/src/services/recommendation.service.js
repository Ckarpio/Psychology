/*
 * =====================================================================
 * recommendation.service.js — СЕРВИС РЕКОМЕНДАЦИЙ (бизнес-логика)
 * =====================================================================
 *
 * Что такое сервис?
 *   Сервис — это файл, в котором живёт "бизнес-логика" приложения.
 *   Бизнес-логика — это ПРАВИЛА, по которым работает приложение.
 *
 *   Например, правило нашего приложения:
 *     "Каждый день пользователь видит один и тот же контент (не меняется
 *      при обновлении страницы). Контент обновляется на следующий день.
 *      Сначала показываем контент, который ещё ни разу не показывали."
 *
 * Зачем отдельный сервис?
 *   Контроллер не должен содержать сложную логику. Его задача —
 *   принять запрос и отправить ответ. А вся "умная" работа — в сервисе.
 *
 *   Если завтра мы захотим получать рекомендации не только через HTTP,
 *   но и, например, через Telegram-бота — мы просто вызовем тот же сервис.
 *   Логику переписывать не придётся.
 * =====================================================================
 */

// ─── Шаг 1: Подключаем репозитории ──────────────────────────────────
// Сервис работает с НЕСКОЛЬКИМИ репозиториями, чтобы собрать нужные данные.
// Каждый репозиторий отвечает за свою таблицу в базе данных.

// emotionsRepo — работает с таблицей emotions (список эмоций)
const emotionsRepo = require('../repositories/emotions.repo');

// picksRepo — работает с таблицей daily_picks (что уже выбрано на сегодня)
const picksRepo = require('../repositories/picks.repo');

// contentRepo — работает с таблицей content_items (библиотека контента)
const contentRepo = require('../repositories/content.repo');

// ─── Шаг 2: Вспомогательная функция для получения сегодняшней даты ──
// todayKey() возвращает строку с сегодняшней датой в формате 'YYYY-MM-DD'.
// Например: '2025-06-15'
//
// Intl.DateTimeFormat — встроенный в JavaScript инструмент для форматирования дат.
// 'en-CA' — канадский английский формат даты, который как раз выдаёт YYYY-MM-DD.
//           (Это удобный трюк: не нужно вручную собирать строку год-месяц-день.)
// .format(new Date()) — форматирует текущую дату.
//
// Зачем нужна дата? Чтобы привязать контент к конкретному дню.
// Один и тот же контент показывается весь день.
function todayKey() {
  return new Intl.DateTimeFormat('en-CA').format(new Date());
}

// ─── Шаг 3: Список типов контента ──────────────────────────────────
// Массив из 5 типов контента. Для каждого типа мы подберём один материал.
// Этот массив используется в цикле ниже.
const CONTENT_TYPES = ['music', 'video', 'images', 'exercises', 'articles'];


// ─── Шаг 4: Функция выбора одного материала ─────────────────────────
// pickForType(emotion, date, type) — подбирает ОДИН материал для конкретной
// комбинации: эмоция + дата + тип контента.
//
// Параметры:
//   emotion — код эмоции (например 'anger')
//   date    — сегодняшняя дата (например '2025-06-15')
//   type    — тип контента (например 'music')
//
// Возвращает: объект с материалом или null (если ничего нет).
function pickForType(emotion, date, type) {

  // ─── Этап 1: Проверяем, есть ли уже выбор на сегодня ────────────
  // picksRepo.getPickedItemId() — ищет в таблице daily_picks запись
  // для данной эмоции, даты и типа.
  //
  // Если нашёл — возвращает id контента (число).
  // Если не нашёл — возвращает null.
  const pickedId = picksRepo.getPickedItemId(emotion, date, type);

  // Если id найден — значит контент уже был выбран ранее сегодня.
  // Достаём полный объект контента по id и возвращаем его.
  // Это обеспечивает "липкость": при повторном запросе в тот же день
  // пользователь увидит тот же контент.
  if (pickedId) return contentRepo.getById(pickedId);

  // ─── Этап 2: Выбираем новый контент ─────────────────────────────
  // Если на сегодня ещё ничего не выбрано — подбираем новый материал.

  // Сначала пробуем найти контент, который НИКОГДА раньше не показывали.
  // getNeverPickedByEmotionType() — ищет материал, id которого
  // ни разу не появлялся в таблице daily_picks.
  // Это даёт разнообразие: сначала покажем всё новое.
  let next = contentRepo.getNeverPickedByEmotionType(emotion, type);

  // Если все материалы уже показывали хотя бы раз — берём любой случайный
  // активный материал. Это запасной вариант, чтобы не показывать пустоту.
  if (!next) next = contentRepo.getAnyActiveByEmotionType(emotion, type);

  // Если вообще нет контента для этой эмоции и типа — возвращаем null.
  if (!next) return null;

  // ─── Этап 3: Сохраняем выбор в daily_picks ──────────────────────
  // Записываем, что на сегодня для этой эмоции и типа выбран этот контент.
  // Это нужно чтобы при повторном запросе вернуть тот же контент (Этап 1).
  try {
    // savePick() — вставляет запись в таблицу daily_picks.
    picksRepo.savePick(emotion, date, type, next.id);
    return next;

  } catch (e) {
    // Если сохранение не удалось — скорее всего, запись уже была создана
    // другим запросом в тот же момент (гонка запросов / race condition).
    //
    // В этом случае читаем то, что уже записано, и возвращаем его.
    const id = picksRepo.getPickedItemId(emotion, date, type);
    return id ? contentRepo.getById(id) : next;
  }
}

// ─── Шаг 5: Главная функция — получить рекомендацию на день ─────────
// getDailyRecommendation(emotion) — собирает полную рекомендацию:
// по одному материалу на каждый из 5 типов контента.
//
// Параметр emotion — код эмоции (например 'anger').
// Возвращает объект с датой, данными эмоции и подобранными материалами.
function getDailyRecommendation(emotion) {

  // ─── Шаг 5.1: Проверяем, существует ли такая эмоция ─────────────
  // getEmotionByCode() — ищет эмоцию в базе по коду.
  // Если нашёл — возвращает объект эмоции.
  // Если не нашёл — возвращает undefined (что в if будет как false).
  const emo = emotionsRepo.getEmotionByCode(emotion);

  // Если эмоция не найдена — создаём ошибку и "выбрасываем" её (throw).
  //
  // new Error('текст') — создаёт объект ошибки с сообщением.
  // err.code = 'NOT_FOUND' — добавляем своё свойство code к ошибке.
  //   Это НЕ стандартное свойство — мы придумали его сами, чтобы контроллер
  //   мог различать типы ошибок (NOT_FOUND → 404, всё остальное → 500).
  //
  // throw err — "выбрасывает" ошибку. Функция прекращает работу,
  //   и ошибка "летит" наверх — в контроллер, где её поймает catch.
  if (!emo) {
    const err = new Error('Неизвестный код эмоции');
    err.code = 'NOT_FOUND';
    throw err;
  }

  // ─── Шаг 5.2: Получаем сегодняшнюю дату ────────────────────────
  const date = todayKey();

  // ─── Шаг 5.3: Создаём объект для сбора результатов ──────────────
  // material — объект, где ключ = тип контента, значение = массив материалов.
  // Начинаем с пустых массивов, потом будем добавлять в них элементы.
  const material = {
    music: [],
    video: [],
    images: [],
    exercises: [],
    articles: [],
  };

  // ─── Шаг 5.4: Цикл по всем типам контента ──────────────────────
  // for...of — проходим по каждому типу из массива CONTENT_TYPES.
  // На каждой итерации type будет: 'music', потом 'video', потом 'images' и т.д.
  for (const type of CONTENT_TYPES) {

    // Вызываем pickForType() — она подберёт один материал
    // для текущей эмоции, даты и типа.
    const item = pickForType(emotion, date, type);

    // Если материал найден (не null) — добавляем его в соответствующий массив.
    if (item) {
      // material[type] — обращение к свойству объекта через переменную.
      // Если type = 'music', то material[type] = material['music'] = material.music
      // .push(item) — добавляем элемент в конец массива.
      material[type].push(item);
      //example material.music = material['music']
    }
  }

  // ─── Шаг 5.5: Возвращаем результат ─────────────────────────────
  // Возвращаем объект с тремя свойствами:
  //   date     — сегодняшняя дата
  //   emotion  — полный объект эмоции из базы (code, label, color и т.д.)
  //   material — объект с подобранным контентом по типам
  return { date, emotion: emo, material };
}

// ─── Шаг 6: Экспортируем ───────────────────────────────────────────
module.exports = { getDailyRecommendation };
