/*
 * =====================================================================
 * recommendation.controller.js — КОНТРОЛЛЕР ДЛЯ РЕКОМЕНДАЦИЙ
 * =====================================================================
 *
 * Обрабатывает запрос: GET /api/recommendation?emotion=anger
 *
 * Этот контроллер сложнее, чем emotions.controller.js, потому что:
 *   1. Нужно проверить, что пользователь передал параметр emotion
 *   2. Нужно вызвать сервис (а не репозиторий напрямую), потому что
 *      логика выбора контента достаточно сложная
 *   3. Нужно обработать возможные ошибки (try/catch)
 * =====================================================================
 */

// ─── Шаг 1: Подключаем сервис рекомендаций ─────────────────────────
// Здесь мы обращаемся к сервису, а не к репозиторию напрямую.
// Сервис содержит бизнес-логику: "как выбрать контент на день".
// Контроллер не должен знать эту логику — он просто вызывает сервис.
const recommendationService = require('../services/recommendation.service');

// ─── Шаг 2: Функция-обработчик для GET /api/recommendation ─────────
async function getRecommendation(req, res) {

  // ─── Шаг 2.1: Извлекаем параметр emotion из URL ────────────────
  // req.query — объект со всеми query-параметрами из URL.
  //
  // Пример URL: /api/recommendation?emotion=anger&lang=ru
  // req.query будет: { emotion: 'anger', lang: 'ru' }
  //
  // req.query.emotion — берём значение параметра emotion.
  // || '' — если emotion не указан (undefined), используем пустую строку.
  //         Это защита от ошибки: без неё String(undefined) дал бы строку "undefined".
  // String(...) — преобразуем в строку (на всякий случай, если вдруг не строка).
  // .trim() — убираем пробелы в начале и конце строки.
  //           Например: "  anger  " → "anger"
  const emotion = String(req.query.emotion || '').trim();

  // ─── Шаг 2.2: Проверяем, что параметр не пустой ────────────────
  // Если emotion — пустая строка (пользователь не передал параметр),
  // возвращаем ошибку 400 (Bad Request — "плохой запрос").
  //
  // res.status(400) — устанавливает HTTP-код ответа 400.
  //   HTTP-коды — это числовые коды, которые говорят клиенту о результате:
  //     200 — всё хорошо (OK)
  //     400 — клиент ошибся (Bad Request) — не передал нужные данные
  //     404 — не найдено (Not Found)
  //     500 — ошибка на сервере (Internal Server Error)
  //
  // .json({ error: '...' }) — отправляем JSON с описанием ошибки.
  //
  // return — ВАЖНО! Прерываем выполнение функции. Без return код продолжит
  // выполняться дальше, даже после отправки ответа, что вызовет ошибку.
  if (!emotion)
    return res.status(400).json({ error: 'Параметр emotion является обязательным' });

  // ─── Шаг 2.3: Вызываем сервис и обрабатываем ошибки ────────────
  // try/catch — конструкция для обработки ошибок.
  //
  //   try { ... }   — "попробуй выполнить этот код"
  //   catch (e) { ... } — "если произошла ошибка, поймай её и обработай"
  //
  // Без try/catch, если внутри getDailyRecommendation() произойдёт ошибка,
  // сервер упадёт (прекратит работу). С try/catch — ошибка "ловится",
  // и мы можем вернуть пользователю понятное сообщение вместо падения.
  try {
    // Вызываем сервис, который подберёт контент на сегодня для данной эмоции.
    // result будет объект вида:
    //   {
    //     date: '2025-01-15',
    //     emotion: { code: 'anger', label: 'Гнев', ... },
    //     material: {
    //       music: [...],
    //       video: [...],
    //       images: [...],
    //       exercises: [...],
    //       articles: [...]
    //     }
    //   }
    const result = recommendationService.getDailyRecommendation(emotion);

    // Отправляем результат клиенту в формате JSON.
    // return — чтобы функция завершилась после отправки ответа.
    return res.json(result);

  } catch (e) {
    // Сюда попадаем, если getDailyRecommendation() выбросил ошибку (throw).

    // Проверяем: если код ошибки 'NOT_FOUND' — значит эмоция не найдена в базе.
    // e.code — свойство, которое мы сами добавили к ошибке в сервисе.
    // Возвращаем 404 (Not Found) с сообщением из ошибки.
    if (e.code === 'NOT_FOUND')
        return res.status(404).json({ error: e.message });

    // Если ошибка другая (непредвиденная) — выводим её в консоль для отладки.
    console.log('Error: ', e.message)

    // Возвращаем клиенту общее сообщение "Внутренняя ошибка" со статусом 500.
    // Мы НЕ отправляем клиенту подробности ошибки (e.message),
    // потому что в них может быть конфиденциальная информация
    // (структура базы данных, пути к файлам и т.д.)
    return res.status(500).json({ error: 'Внутренняя ошибка' });
  }
}

// ─── Шаг 3: Экспортируем ───────────────────────────────────────────
module.exports = { getRecommendation };
