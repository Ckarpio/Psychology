/*
 * =====================================================================
 * emotions.controller.js — КОНТРОЛЛЕР ДЛЯ ЭМОЦИЙ
 * =====================================================================
 *
 * Что такое контроллер?
 *   Контроллер — это "посредник" между маршрутом (URL) и данными.
 *   Он получает HTTP-запрос от пользователя, просит данные у репозитория
 *   (или сервиса), и отправляет HTTP-ответ обратно пользователю.
 *
 * Аналогия: контроллер — это официант в ресторане.
 *   1. Принимает заказ от клиента (получает HTTP-запрос)
 *   2. Передаёт заказ на кухню (вызывает репозиторий/сервис)
 *   3. Приносит готовое блюдо клиенту (отправляет HTTP-ответ)
 *
 * Контроллер НЕ знает, как именно хранятся данные (SQL-запросы).
 * Этим занимается репозиторий. Контроллер просто вызывает его функции.
 * =====================================================================
 */

// ─── Шаг 1: Подключаем репозиторий эмоций ──────────────────────────
// emotionsRepo — объект с функциями для работы с таблицей emotions.
// Репозиторий "знает" SQL и умеет доставать данные из базы.
const emotionsRepo = require('../repositories/emotions.repo');

// ─── Шаг 2: Функция-обработчик для GET /api/emotions ────────────────
// Эта функция вызывается Express'ом когда приходит GET-запрос на /api/emotions.
//
// Express автоматически передаёт два аргумента:
//   req (request)  — объект запроса. Содержит информацию о том, что запросил клиент:
//                    URL, параметры, заголовки, тело запроса и т.д.
//   res (response) — объект ответа. Через него мы отправляем данные обратно клиенту.
//
// async — ключевое слово, которое позволяет использовать await внутри функции.
// В данном случае await не используется (better-sqlite3 работает синхронно),
// но async не мешает — функция просто работает как обычная.
async function getAllEmotions(req, res) {

  // Вызываем функцию getAllEmotions() из репозитория.
  // Она выполняет SQL-запрос к базе данных и возвращает массив всех эмоций.
  // Результат — массив объектов, например:
  //   [
  //     { code: 'anger', label: 'Гнев', effect: 'negative', ... },
  //     { code: 'sadness', label: 'Грусть', effect: 'negative', ... },
  //     ...
  //   ]
  const dbResult = emotionsRepo.getAllEmotions();

  // res.json(dbResult) — отправляет данные клиенту в формате JSON.
  //
  // JSON (JavaScript Object Notation) — универсальный формат для обмена данными.
  // res.json() делает две вещи:
  //   1. Преобразует JavaScript-объект/массив в JSON-строку
  //   2. Устанавливает заголовок Content-Type: application/json
  //   3. Отправляет ответ клиенту
  //
  // Если не указать статус, Express по умолчанию вернёт статус 200 (OK).
  res.json(dbResult);
}

// ─── Шаг 3: Экспортируем функцию ───────────────────────────────────
// Делаем функцию доступной для файла emotions.routes.js,
// который подключит её к маршруту.
module.exports = { getAllEmotions };
