/*
 * =====================================================================
 * emotions.repo.js — РЕПОЗИТОРИЙ ДЛЯ РАБОТЫ С ЭМОЦИЯМИ
 * =====================================================================
 *
 * Что такое репозиторий?
 *   Репозиторий — это файл, который "знает" как работать с базой данных.
 *   Он содержит SQL-запросы и возвращает готовые данные.
 *
 *   Аналогия: репозиторий — это библиотекарь.
 *   Ты говоришь ему "дай все книги по психологии", а он знает
 *   в каком шкафу искать, на какой полке, и приносит тебе их.
 *   Тебе не нужно знать, как устроена библиотека — библиотекарь сам разберётся.
 *
 * Зачем отдельные файлы-репозитории?
 *   Чтобы SQL-запросы были в одном месте. Если нужно изменить запрос —
 *   меняем только здесь, а контроллеры и сервисы не трогаем.
 *
 * Этот файл отвечает за таблицу emotions.
 * =====================================================================
 */

// ─── Шаг 1: Подключаем функцию для получения базы данных ────────────
// getDb() — возвращает объект подключения к SQLite (из db/index.js).
// Через этот объект мы выполняем SQL-запросы.
const { getDb } = require('../db');

// ─── Шаг 2: Функция — получить все эмоции ───────────────────────────
// getAllEmotions() — возвращает массив ВСЕХ эмоций из таблицы.
function getAllEmotions() {
  // getDb() — получаем подключение к базе данных.
  const db = getDb();

  // db.prepare(sql) — подготавливает SQL-запрос.
  //
  // SELECT — команда SQL для получения данных (чтение).
  //   SELECT code, label, effect, color, ico, description
  //   — выбираем конкретные колонки (можно было написать SELECT *,
  //     но перечисление колонок делает код понятнее — видно что мы получаем).
  //
  //   FROM emotions — из таблицы emotions.
  //
  // .all() — выполняет запрос и возвращает ВСЕ найденные строки
  //          в виде массива объектов.
  //
  // Результат: [
  //   { code: 'anger', label: 'Гнев', effect: 'negative', color: 'orange', ... },
  //   { code: 'sadness', label: 'Грусть', effect: 'negative', color: 'blue', ... },
  //   ...
  // ]
  //
  // Если таблица пустая — вернётся пустой массив [].
  return db.prepare(`
    SELECT code,label,effect,color,ico,description
    FROM emotions
  `).all();
}

// ─── Шаг 3: Функция — получить одну эмоцию по коду ──────────────────
// getEmotionByCode(code) — ищет эмоцию с конкретным кодом.
//
// Параметр code — строка, например 'anger' или 'joy'.
function getEmotionByCode(code) {
  const db = getDb();

  // SELECT ... WHERE code = ?
  //   WHERE — фильтр. Выбирает только те строки, где значение колонки code
  //           совпадает с тем, что мы передадим.
  //
  //   ? — это ПАРАМЕТР (placeholder / заполнитель).
  //   Вместо того чтобы писать WHERE code = 'anger' прямо в SQL-строке,
  //   мы ставим ? и передаём значение отдельно через .get(code).
  //
  //   Зачем? Это защита от SQL-инъекции — атаки, при которой злоумышленник
  //   может вставить вредоносный SQL-код через пользовательский ввод.
  //   С параметром ? база данных ТОЧНО знает, что это просто значение,
  //   а не SQL-команда.
  //
  //   Пример SQL-инъекции (если бы мы писали code прямо в строку):
  //     WHERE code = '' OR 1=1 --   ← это вернёт ВСЕ записи!
  //
  //   С параметром ? это невозможно — база воспримет всю строку как значение.
  //
  // .get(code) — выполняет запрос, подставляя code вместо ?,
  //   и возвращает ОДНУ строку (первую найденную) в виде объекта.
  //   Если ничего не найдено — возвращает undefined.
  //
  // Разница между .all() и .get():
  //   .all()  → массив всех строк: [{...}, {...}, ...]
  //   .get()  → одна строка (объект): {...}   или undefined
  return db.prepare(`
    SELECT code,label,effect,color,ico,description
    FROM emotions
    WHERE code = ?
  `).get(code);
}

// ─── Шаг 4: Экспортируем функции ───────────────────────────────────
// Другие файлы (контроллеры, сервисы) смогут импортировать эти функции.
module.exports = { getAllEmotions, getEmotionByCode };
