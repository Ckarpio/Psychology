/*
 * =====================================================================
 * content.repo.js — РЕПОЗИТОРИЙ ДЛЯ РАБОТЫ С КОНТЕНТОМ
 * =====================================================================
 *
 * Этот файл работает с таблицей content_items — библиотекой контента.
 * Содержит три функции для поиска материалов:
 *
 *   1. getById(id)
 *      — найти конкретный материал по его уникальному номеру (id)
 *
 *   2. getAnyActiveByEmotionType(emotion, type)
 *      — найти случайный активный материал по эмоции и типу
 *
 *   3. getNeverPickedByEmotionType(emotion, type)
 *      — найти материал, который ещё ни разу не показывали пользователю
 * =====================================================================
 */

// ─── Шаг 1: Подключаем базу данных ─────────────────────────────────
const { getDb } = require('../db');

// ─── Шаг 2: Найти материал по id ───────────────────────────────────
// getById(id) — возвращает один материал по его уникальному номеру.
//
// Используется когда мы уже знаем id (например, из таблицы daily_picks).
function getById(id) {
  const db = getDb();

  // SELECT * — выбрать ВСЕ колонки из таблицы.
  // * (звёздочка) означает "всё". Это короче, чем перечислять каждую колонку.
  //
  // WHERE id = ? — ищем строку с конкретным id.
  // .get(id) — подставляем id вместо ? и возвращаем одну строку.
  return db.prepare(`SELECT * FROM content_items WHERE id = ?`).get(id);
}

// ─── Шаг 3: Найти случайный активный материал ──────────────────────
// getAnyActiveByEmotionType(emotion, type) — возвращает один случайный
// активный материал для указанной эмоции и типа.
//
// "Активный" означает is_active = 1 (материал включён).
// Это запасной вариант: используется когда все материалы уже были показаны.
function getAnyActiveByEmotionType(emotion, type) {
  const db = getDb();

  // Этот SQL-запрос:
  //
  // SELECT * FROM content_items — выбираем все колонки из таблицы контента
  //
  // WHERE emotion_code = ?     — фильтр по эмоции (первый ?)
  //   AND type = ?             — фильтр по типу контента (второй ?)
  //   AND is_active = 1        — только включённый контент
  //
  // ORDER BY RANDOM()          — сортируем в случайном порядке.
  //   RANDOM() — функция SQLite, которая даёт случайное число.
  //   Каждая строка получит своё случайное число, и строки отсортируются по нему.
  //   В итоге строки перемешаются в случайном порядке.
  //
  // LIMIT 1                    — берём только первую строку из результата.
  //   В сочетании с ORDER BY RANDOM() это даёт нам одну случайную строку.
  //
  // .get(emotion, type) — подставляет значения вместо ? (по порядку):
  //   первый ?  → emotion
  //   второй ?  → type
  return db.prepare(`
    SELECT *
    FROM content_items
    WHERE emotion_code = ?
      AND type = ?
      AND is_active = 1
    ORDER BY RANDOM()
    LIMIT 1
  `).get(emotion, type);
}

// ─── Шаг 4: Найти материал, который ещё ни разу не показывали ───────
// getNeverPickedByEmotionType(emotion, type) — возвращает один случайный
// материал, который ни разу не появлялся в таблице daily_picks.
//
// Это основной способ выбора контента. Он гарантирует разнообразие:
// каждый день пользователь видит что-то новое (пока не покажем всё).
function getNeverPickedByEmotionType(emotion, type) {
  const db = getDb();

  // Этот SQL-запрос более сложный, потому что использует JOIN.
  //
  // ─── Что такое JOIN? ────────────────────────────────────────────
  // JOIN — это способ объединить данные из двух таблиц в одном запросе.
  //
  // Представь две Excel-таблицы:
  //   Таблица А (content_items): id=1, title="Плейлист: Гнев"
  //   Таблица Б (daily_picks):   content_item_id=1, pick_date="2025-01-15"
  //
  // JOIN соединяет строки из таблицы А со строками из таблицы Б,
  // если выполняется условие (ON ...).
  //
  // LEFT JOIN — особый вид JOIN:
  //   - Берёт ВСЕ строки из левой таблицы (content_items)
  //   - Для каждой строки ищет совпадение в правой таблице (daily_picks)
  //   - Если совпадение есть — присоединяет данные из правой таблицы
  //   - Если совпадения НЕТ — ставит NULL (пусто) для полей правой таблицы
  //
  // ─── Разбор запроса построчно ───────────────────────────────────
  //
  // SELECT ci.* — выбираем все колонки из content_items (алиас ci)
  //
  // FROM content_items ci — основная таблица, алиас (сокращение) ci
  //   Алиас — это короткое имя для таблицы, чтобы не писать полное название.
  //   Вместо content_items.id можно писать ci.id
  //
  // LEFT JOIN daily_picks dp — присоединяем таблицу daily_picks (алиас dp)
  //
  //   ON ci.id = dp.content_item_id  — условие соединения:
  //     "соедини строки, где id контента совпадает с content_item_id в daily_picks"
  //   AND dp.emotion_code = ?        — дополнительный фильтр:
  //     "только для этой эмоции" (первый параметр ?)
  //   AND dp.type = ?                — "и для этого типа" (второй параметр ?)
  //
  // WHERE ci.emotion_code = ?  — фильтр по эмоции (третий ?)
  //   AND ci.type = ?          — фильтр по типу (четвёртый ?)
  //   AND ci.is_active = 1     — только включённый контент
  //   AND dp.content_item_id IS NULL  — ← КЛЮЧЕВОЕ УСЛОВИЕ!
  //
  //   IS NULL означает "значение пусто". Помнишь, LEFT JOIN ставит NULL
  //   для полей правой таблицы, если совпадения нет?
  //   dp.content_item_id IS NULL → контент, который НЕ найден в daily_picks
  //   → контент, который ещё НИКОГДА не показывали!
  //
  // ORDER BY RANDOM() LIMIT 1 — случайный один из таких "новых" материалов.
  //
  // .get(emotion, type, emotion, type) — четыре параметра для четырёх ?
  //   Обрати внимание: emotion и type передаются ДВАЖДЫ,
  //   потому что они используются и в ON (для JOIN), и в WHERE (для фильтра).
  return db.prepare(`
    SELECT ci.*
    FROM content_items ci
    LEFT JOIN daily_picks dp
      ON ci.id = dp.content_item_id
      AND dp.emotion_code = ?
      AND dp.type = ?
    WHERE ci.emotion_code = ?
      AND ci.type = ?
      AND ci.is_active = 1
      AND dp.content_item_id IS NULL
    ORDER BY RANDOM()
    LIMIT 1
  `).get(emotion, type, emotion, type);
}

// ─── Шаг 5: Экспортируем функции ───────────────────────────────────
module.exports = {
  getById,
  getAnyActiveByEmotionType,
  getNeverPickedByEmotionType,
};
