/*
 * =====================================================================
 * app.js — ГЛАВНЫЙ ФАЙЛ СЕРВЕРА (точка входа)
 * =====================================================================
 *
 * Это самый первый файл, который запускается когда мы пишем "npm start".
 * Его задача — собрать все части приложения вместе и запустить сервер,
 * который будет слушать запросы от браузера (от клиента).
 *
 * Порядок чтения файлов сервера:
 *   1. package.json        — какие библиотеки мы используем
 *   2. src/db/schema.js    — как выглядят таблицы в базе данных
 *   3. src/db/index.js     — подключение к базе данных
 *   4. src/db/seed.js      — заполнение базы тестовыми данными
 *   5. src/app.js          — ТЫ ЗДЕСЬ. Главный файл сервера
 *   6. src/routes/         — маршруты (какие URL-адреса существуют)
 *   7. src/controllers/    — контроллеры (что делать при запросе)
 *   8. src/services/       — сервисы (бизнес-логика)
 *   9. src/repositories/   — репозитории (запросы к базе данных)
 * =====================================================================
 */

// ─── Шаг 1: Подключаем библиотеку Express ──────────────────────────
// require('express') — загружает библиотеку Express из папки node_modules.
// Express — это фреймворк (набор готовых инструментов) для создания серверов.
// Без него нам пришлось бы вручную разбирать HTTP-запросы, а Express
// делает это за нас и даёт удобные методы вроде app.get(), app.use() и т.д.
const express = require('express');

// ─── Шаг 2: Подключаем наши модули ─────────────────────────────────
// initDb — функция, которая создаёт (или открывает) базу данных
// и создаёт в ней таблицы, если их ещё нет.
// Мы написали её сами в файле ./db/index.js
const { initDb } = require('./db');

// routes — объект, в котором описаны все URL-адреса нашего сервера
// (например /api/emotions, /api/recommendation).
// Мы написали его в файле ./routes/index.js
const routes = require('./routes');

// ─── Шаг 3: Создаём приложение Express ─────────────────────────────
// express() — вызываем функцию express как конструктор.
// Она возвращает объект "app", который и есть наш сервер.
// Теперь мы можем настраивать этот сервер: добавлять маршруты,
// middleware (промежуточные обработчики) и т.д.
const app = express();

// ─── Шаг 4: Подключаем middleware для работы с JSON ─────────────────
// Middleware — это функция, которая обрабатывает каждый входящий запрос
// ПЕРЕД тем, как он попадёт в наш код.
//
// express.json() — это встроенный middleware, который:
//   1. Смотрит на тело (body) входящего запроса
//   2. Если там JSON-строка (например '{"emotion":"anger"}'),
//      он преобразует её в обычный JavaScript-объект
//   3. Кладёт этот объект в req.body, чтобы мы могли им пользоваться
//
// Без этой строки req.body был бы undefined при POST/PUT запросах.
app.use(express.json());

// ─── Шаг 5: Инициализируем базу данных ─────────────────────────────
// initDb() — вызываем нашу функцию из ./db/index.js.
// Она делает две вещи:
//   1. Открывает (или создаёт) файл app.db — это файл базы данных SQLite
//   2. Выполняет SQL-запросы из schema.js, которые создают таблицы
//      (emotions, content_items, daily_picks), если их ещё нет
//
// Важно: мы вызываем initDb() ДО того, как сервер начнёт принимать запросы,
// чтобы база данных точно была готова к работе.
initDb();

// ─── Шаг 6: Подключаем маршруты ────────────────────────────────────
// app.use('/api', routes) — говорим серверу:
//   "Все запросы, которые начинаются с /api, обрабатывай с помощью routes"
//
// Например:
//   GET /api/emotions       → попадёт в routes, а оттуда в emotions.routes.js
//   GET /api/recommendation → попадёт в routes, а оттуда в recommendation.routes.js
//
// Префикс '/api' добавляется автоматически ко всем маршрутам внутри routes.
// Поэтому в самих файлах маршрутов мы пишем просто '/', а не '/api/emotions'.
app.use('/api', routes);

// ─── Шаг 7: Запускаем сервер ────────────────────────────────────────
// app.listen(порт, колбэк) — запускает сервер на указанном порту.
//
// Порт — это как номер двери в здании. Компьютер — это здание,
// а порт 3000 — конкретная дверь, через которую приходят запросы.
//
// После запуска сервер будет бесконечно ждать входящих запросов.
// Когда придёт запрос — он обработает его и отправит ответ.
//
// Второй аргумент — это колбэк-функция (callback).
// Она вызывается ОДИН РАЗ, когда сервер успешно запустился.
// Мы просто выводим в консоль ссылку, чтобы знать что всё работает.
app.listen(3000, () => console.log('API: http://localhost:3000'));
