/*
 * =====================================================================
 * schema.js — СТРУКТУРА БАЗЫ ДАННЫХ (какие таблицы существуют)
 * =====================================================================
 *
 * Этот файл описывает СХЕМУ базы данных — то есть какие таблицы
 * существуют и какие колонки (поля) в каждой таблице.
 *
 * Можно думать о таблицах как об Excel-таблицах:
 *   - Таблица = отдельный лист в Excel
 *   - Колонка = столбец (например "Имя", "Возраст")
 *   - Строка  = одна запись (один ряд данных)
 *
 * SQL (Structured Query Language) — это язык для работы с базами данных.
 * CREATE TABLE — команда SQL, которая создаёт новую таблицу.
 *
 * IF NOT EXISTS — означает "создай таблицу только если её ещё нет".
 * Без этого при повторном запуске была бы ошибка "таблица уже существует".
 * =====================================================================
 */

// module.exports.SCHEMA_SQL — мы экспортируем (делаем доступной для других файлов)
// переменную SCHEMA_SQL. Это просто длинная строка с SQL-командами.
// Обратные кавычки `` позволяют писать многострочные строки в JavaScript.
module.exports.SCHEMA_SQL = `

/* ════════════════════════════════════════════════════════════════════
 * ТАБЛИЦА 1: emotions (эмоции)
 * ════════════════════════════════════════════════════════════════════
 * Хранит список всех эмоций, с которыми работает приложение.
 * Например: гнев, грусть, радость, любовь и т.д.
 *
 * Каждая эмоция имеет:
 *   code        — уникальный код на английском (anger, joy, sadness...)
 *                 TEXT PRIMARY KEY означает что это главный ключ таблицы.
 *                 Первичный ключ — это уникальный идентификатор строки.
 *                 Два одинаковых code не может быть — база данных не позволит.
 *
 *   label       — название на русском ("Гнев", "Радость"...)
 *                 NOT NULL означает "обязательное поле" — нельзя оставить пустым.
 *
 *   effect      — тип эмоции: "negative" или "positive"
 *                 NOT NULL — тоже обязательное поле.
 *
 *   color       — цвет для отображения в интерфейсе (orange, blue, yellow...)
 *                 Без NOT NULL — значит поле необязательное (может быть пустым).
 *
 *   ico         — путь к иконке эмоции (пока не используется)
 *
 *   description — описание эмоции на русском языке
 */
CREATE TABLE IF NOT EXISTS emotions (
  code TEXT PRIMARY KEY,
  label TEXT NOT NULL,
  effect TEXT NOT NULL,
  color TEXT,
  ico TEXT,
  description TEXT
);

/* ════════════════════════════════════════════════════════════════════
 * ТАБЛИЦА 2: content_items (контент / материалы)
 * ════════════════════════════════════════════════════════════════════
 * Хранит все материалы, которые можно показать пользователю.
 * Это как большая библиотека: музыка, видео, картинки, упражнения, статьи.
 *
 * Каждый материал привязан к конкретной эмоции через поле emotion_code.
 *
 * Поля:
 *   id           — уникальный номер записи, автоматически увеличивается на 1
 *                  INTEGER PRIMARY KEY AUTOINCREMENT — база сама присвоит номер
 *                  Первая запись получит id=1, вторая id=2 и т.д.
 *
 *   emotion_code — код эмоции, к которой привязан этот контент (например 'anger')
 *                  TEXT NOT NULL — обязательное текстовое поле
 *
 *   type         — тип контента. Один из пяти вариантов:
 *                  music | video | image | exercise | article
 *
 *   title        — заголовок материала
 *   subtitle     — подзаголовок (краткое описание)
 *   url          — ссылка на внешний ресурс (для музыки, видео, статей)
 *   image_url    — ссылка на картинку
 *   body         — основной текст материала
 *
 *   is_active    — включён ли материал (1 = да, 0 = нет)
 *                  DEFAULT 1 означает что по умолчанию материал включён.
 *                  Это позволяет "выключить" материал, не удаляя его из базы.
 *
 *   created_at   — дата и время создания записи
 *                  DEFAULT (datetime('now')) — автоматически ставится текущее время
 *
 *   FOREIGN KEY  — внешний ключ. Это связь между таблицами.
 *                  Говорит базе данных: "значение emotion_code должно существовать
 *                  в таблице emotions в колонке code".
 *                  Нельзя добавить контент для эмоции, которой нет в таблице emotions.
 */
CREATE TABLE IF NOT EXISTS content_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  emotion_code TEXT NOT NULL,
  type TEXT NOT NULL,
  title TEXT NOT NULL,
  subtitle TEXT,
  url TEXT,
  image_url TEXT,
  body TEXT,
  is_active INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  FOREIGN KEY (emotion_code) REFERENCES emotions(code)
);

/* ════════════════════════════════════════════════════════════════════
 * УНИКАЛЬНЫЙ ИНДЕКС для content_items
 * ════════════════════════════════════════════════════════════════════
 * CREATE UNIQUE INDEX — создаёт правило: комбинация (emotion_code + type + title)
 * должна быть уникальной. То есть не может быть двух записей с одинаковой
 * эмоцией, типом и заголовком одновременно.
 *
 * Пример: запись (anger, music, "Плейлист: Гнев") может быть только одна.
 * Если попытаться добавить такую же — база данных выдаст ошибку.
 *
 * Зачем: чтобы при повторном запуске seed.js не создавались дубликаты.
 */
CREATE UNIQUE INDEX IF NOT EXISTS uq_content_unique
ON content_items(emotion_code, type, title);


/* ════════════════════════════════════════════════════════════════════
 * ТАБЛИЦА 3: daily_picks (выбор контента на день)
 * ════════════════════════════════════════════════════════════════════
 * Эта таблица запоминает, какой контент был показан пользователю
 * в конкретный день для конкретной эмоции и типа контента.
 *
 * Зачем: чтобы в течение одного дня пользователь видел одни и те же
 * материалы (а не новые при каждом обновлении страницы).
 * На следующий день контент обновится.
 *
 * Поля:
 *   id              — уникальный номер записи (автоинкремент)
 *   emotion_code    — для какой эмоции был выбор
 *   pick_date       — дата выбора в формате YYYY-MM-DD (например '2025-01-15')
 *   type            — тип контента (music, video, image, exercise, article)
 *   content_item_id — id выбранного материала из таблицы content_items
 *   created_at      — когда была создана запись
 *
 *   Два FOREIGN KEY:
 *     1. emotion_code → ссылается на emotions.code
 *     2. content_item_id → ссылается на content_items.id
 *   Это гарантирует что мы не можем ссылаться на несуществующие записи.
 */
CREATE TABLE IF NOT EXISTS daily_picks (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  emotion_code TEXT NOT NULL,
  pick_date TEXT NOT NULL,       -- YYYY-MM-DD
  type TEXT NOT NULL,            -- music | video | image | exercise | article
  content_item_id INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  FOREIGN KEY (emotion_code) REFERENCES emotions(code),
  FOREIGN KEY (content_item_id) REFERENCES content_items(id)
);

`;
