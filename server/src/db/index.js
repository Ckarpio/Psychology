/*
 * =====================================================================
 * db/index.js — ПОДКЛЮЧЕНИЕ К БАЗЕ ДАННЫХ
 * =====================================================================
 *
 * Этот файл отвечает за создание и хранение подключения к базе данных.
 *
 * Что такое база данных?
 *   База данных — это место, где хранятся данные приложения.
 *   Представь Excel-файл, в котором есть несколько листов (таблиц),
 *   и на каждом листе — строки с данными. Только база данных
 *   умеет быстро искать, фильтровать и изменять эти данные.
 *
 * Мы используем SQLite — это база данных, которая хранится
 * в одном файле (app.db). Не нужно ничего устанавливать отдельно.
 *
 * Библиотека better-sqlite3 — это инструмент, который позволяет
 * JavaScript-коду общаться с SQLite базой данных.
 * =====================================================================
 */

// ─── Шаг 1: Подключаем библиотеку для работы с SQLite ──────────────
// require('better-sqlite3') загружает библиотеку из node_modules.
// Database — это класс (конструктор). С его помощью мы создаём
// подключение к файлу базы данных.
const Database = require('better-sqlite3');

// ─── Шаг 2: Подключаем схему базы данных ────────────────────────────
// SCHEMA_SQL — это строка с SQL-командами для создания таблиц.
// Мы описали её в файле schema.js
const { SCHEMA_SQL } = require('./schema');

// ─── Шаг 3: Переменная для хранения подключения ─────────────────────
// let db — переменная, в которой будет храниться объект подключения
// к базе данных. Сначала она пустая (undefined).
//
// Мы используем let (а не const), потому что значение будет присвоено позже,
// внутри функции initDb().
let db;

// ─── Шаг 4: Функция инициализации базы данных ──────────────────────
// initDb() — создаёт подключение к базе и создаёт таблицы.
// Вызывается один раз при запуске сервера (в app.js).
function initDb() {
  // Проверяем: если db уже создан — не создаём заново, а возвращаем его.
  // Это называется "паттерн синглтон" (Singleton) — гарантирует что
  // подключение к базе создаётся только один раз.
  //
  // Зачем? Если создать два подключения — они могут конфликтовать друг с другом.
  if (db) return db;

  // new Database('app.db') — создаём новое подключение к файлу app.db
  // Если файл не существует — он будет создан автоматически.
  // Если файл уже есть — просто откроет его.
  db = new Database('app.db');

  // db.exec(SCHEMA_SQL) — выполняет SQL-команды из schema.js.
  // exec() может выполнить сразу несколько SQL-команд в одной строке.
  // Здесь он создаёт три таблицы: emotions, content_items, daily_picks.
  //
  // Благодаря "IF NOT EXISTS" в SQL-запросах, если таблицы уже существуют,
  // ничего не произойдёт — они не пересоздадутся и данные не потеряются.
  db.exec(SCHEMA_SQL);

  // Возвращаем объект подключения к базе.
  return db;
}

// ─── Шаг 5: Функция для получения подключения к базе ────────────────
// getDb() — возвращает текущее подключение к базе данных.
// Вызывается из репозиториев (файлы в папке repositories/),
// когда им нужно выполнить SQL-запрос.
function getDb() {
  // Если по какой-то причине db ещё не создан — создаём его.
  // Это страховка: даже если забыли вызвать initDb(), база всё равно создастся.
  if (!db) initDb();

  // Возвращаем объект подключения.
  return db;
}

// ─── Шаг 6: Экспортируем функции ────────────────────────────────────
// module.exports — делает функции доступными для других файлов.
// Теперь любой файл может написать:
//   const { initDb, getDb } = require('./db');
// и использовать эти функции.
module.exports = { initDb, getDb };
